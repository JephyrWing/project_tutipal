-- PT-96: never guess the historical accepting teacher of an existing help request.
ALTER TABLE help_requests
    ADD COLUMN accepted_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    ADD COLUMN next_chat_sequence BIGINT NOT NULL DEFAULT 1 CHECK (next_chat_sequence > 0);

CREATE TABLE help_chat_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    help_id BIGINT NOT NULL REFERENCES help_requests(id) ON DELETE CASCADE,
    sequence BIGINT NOT NULL CHECK (sequence > 0),
    sender_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    client_message_id UUID NOT NULL,
    message_text TEXT NOT NULL CHECK (char_length(message_text) BETWEEN 1 AND 1000),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_help_chat_order UNIQUE (help_id, sequence),
    CONSTRAINT uk_help_chat_retry UNIQUE (help_id, sender_id, client_message_id)
);
