CREATE TABLE quiz_draft_approvals (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id            BIGINT NOT NULL REFERENCES study_sessions (id),
    teacher_id            BIGINT NOT NULL REFERENCES users (id),
    approved_type         VARCHAR(20) CHECK (approved_type IN ('CHOICE', 'TEXT')),
    approved_question     VARCHAR(1000),
    approved_choices      TEXT[],
    approved_answer_index INTEGER,
    approved_model_answer VARCHAR(2000),
    sent_quiz_id          BIGINT UNIQUE REFERENCES quizzes (id)
);

CREATE INDEX idx_quiz_draft_unsent_session ON quiz_draft_approvals (session_id)
    WHERE sent_quiz_id IS NULL;

ALTER TABLE quiz_answers
    ADD COLUMN ai_original_correct BOOLEAN,
    ADD COLUMN ai_original_feedback VARCHAR(500);

-- 기존 현재 판정 중 출처가 AI로 보존된 주관식 답안만 원판정으로 옮긴다.
UPDATE quiz_answers a
SET ai_original_correct = a.correct, ai_original_feedback = a.feedback
FROM quizzes q
WHERE a.quiz_id = q.id AND q.type = 'TEXT'
  AND a.graded_by = 'AI' AND a.correct IS NOT NULL;
