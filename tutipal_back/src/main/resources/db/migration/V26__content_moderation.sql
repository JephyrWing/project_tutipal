ALTER TABLE posts
    ADD COLUMN hidden_at TIMESTAMP(6) WITH TIME ZONE,
    ADD COLUMN moderation_version BIGINT NOT NULL DEFAULT 0;

ALTER TABLE materials
    ADD COLUMN hidden_at TIMESTAMP(6) WITH TIME ZONE,
    ADD COLUMN moderation_version BIGINT NOT NULL DEFAULT 0;

CREATE TABLE content_moderation_actions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind VARCHAR(8) NOT NULL CHECK (kind IN ('POST', 'MATERIAL')),
    content_id BIGINT NOT NULL,
    session_id BIGINT NOT NULL,
    actor_id BIGINT NOT NULL REFERENCES users (id),
    version BIGINT NOT NULL CHECK (version > 0),
    hidden BOOLEAN NOT NULL,
    reason VARCHAR(300) NOT NULL CHECK (length(trim(reason)) > 0),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    UNIQUE (kind, content_id, version)
);
