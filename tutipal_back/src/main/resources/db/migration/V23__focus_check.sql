-- PT-90: student focus check. Only while the student agreed and started collection, the desktop app sends one row per
-- minute (most used exe basename, idle seconds, foreground switches). The server adds the model category and keeps
-- the latest reference state per student. Everything goes with its user or study session (ON DELETE CASCADE);
-- AccountCleanup also deletes these rows first, and FocusRetention deletes rows of sessions that ended more than
-- app.focus.retention-days (30) ago, and in any session (also one never closed) samples older than
-- app.focus.max-sample-age-days (31) and states not updated for that long. V22 is reserved by PT-87.

CREATE TABLE focus_consents (
    user_id BIGINT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    version VARCHAR(20) NOT NULL,
    consented_at TIMESTAMPTZ NOT NULL
);

CREATE TABLE focus_samples (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES study_sessions(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    -- server minute (floor), never the client's clock
    minute_at TIMESTAMPTZ NOT NULL,
    -- lowercase basename only, same rule as the API; NULL = unknown
    exe_name VARCHAR(68) CHECK (exe_name ~ '^[a-z0-9._-]{1,64}\.exe$'),
    category VARCHAR(10) NOT NULL CHECK (category IN ('ide', 'browser', 'terminal', 'game', 'chat', 'other')),
    idle_sec SMALLINT NOT NULL CHECK (idle_sec BETWEEN 0 AND 60),
    switch_count SMALLINT NOT NULL CHECK (switch_count BETWEEN 0 AND 120),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (session_id, user_id, minute_at)
);

-- account deletion and consent withdrawal delete by user
CREATE INDEX idx_focus_samples_user ON focus_samples (user_id);
-- age upper bound of the hourly retention job
CREATE INDEX idx_focus_samples_minute ON focus_samples (minute_at);

CREATE TABLE focus_states (
    session_id BIGINT NOT NULL REFERENCES study_sessions(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    -- NOT_PARTICIPATING is computed when reading (no row or stale), never stored
    state VARCHAR(12) NOT NULL CHECK (state IN ('FOCUS', 'DISTRACTED', 'BREAK', 'UNKNOWN', 'PENDING')),
    model_version VARCHAR(64),
    updated_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (session_id, user_id)
);

CREATE INDEX idx_focus_states_user ON focus_states (user_id);
