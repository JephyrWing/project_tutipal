-- PT-87: concept tags per quiz, and the raw student questions used for topic clustering.
-- New tables only: no change to existing tables and no backfill. (V20 = PT-86, V21 = PT-106 are reserved.)

-- Concepts a teacher defined in one session. normalized_name = lower case + collapsed spaces (computed in Spring).
CREATE TABLE session_concepts (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id      BIGINT       NOT NULL REFERENCES study_sessions (id) ON DELETE CASCADE,
    name            VARCHAR(30)  NOT NULL CHECK (char_length(btrim(name)) BETWEEN 1 AND 30),
    normalized_name VARCHAR(30)  NOT NULL,
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT uk_session_concept_name UNIQUE (session_id, normalized_name)
);

-- Quiz <-> concept tags. source AI = a suggestion the teacher accepted.
CREATE TABLE quiz_concepts (
    quiz_id    BIGINT      NOT NULL REFERENCES quizzes (id) ON DELETE CASCADE,
    concept_id BIGINT      NOT NULL REFERENCES session_concepts (id) ON DELETE CASCADE,
    source     VARCHAR(10) NOT NULL CHECK (source IN ('TEACHER', 'AI')),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    PRIMARY KEY (quiz_id, concept_id)
);
CREATE INDEX idx_quiz_concepts_concept ON quiz_concepts (concept_id);

-- Raw student chatbot questions (session STUDENT turns only). Temporary retention: rows older than
-- app.insights.questions.retention are deleted by QuestionRetentionJob. No vector column: embeddings are computed
-- on demand and never stored.
CREATE TABLE chat_questions (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id    BIGINT NOT NULL REFERENCES study_sessions (id) ON DELETE CASCADE,
    user_id       BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    question_text TEXT   NOT NULL CHECK (char_length(question_text) BETWEEN 1 AND 1000),
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL
);
CREATE INDEX idx_chat_questions_session ON chat_questions (session_id, id);
CREATE INDEX idx_chat_questions_created ON chat_questions (created_at);
-- account deletion (AccountCleanup) and the users FK cascade look rows up by user
CREATE INDEX idx_chat_questions_user ON chat_questions (user_id);
