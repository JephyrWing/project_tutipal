-- PT-106: server-side AI conversations (raw messages, summaries, user-saved memories).
-- Everything is removed with its user or study session through ON DELETE CASCADE, so AccountCleanup
-- needs no extra DELETE line. Retention (PT-13) is undecided: rows stay until the user deletes them.
-- V20 is reserved by PT-86 (chunk provenance).

CREATE TABLE ai_conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    -- NULL = personal study conversation
    session_id BIGINT REFERENCES study_sessions(id) ON DELETE CASCADE,
    topic VARCHAR(30) NOT NULL CHECK (char_length(topic) BETWEEN 1 AND 30),
    -- first question, first 40 characters; NULL until the first turn is saved
    title VARCHAR(100),
    message_count INT NOT NULL DEFAULT 0 CHECK (message_count >= 0),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_message_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_ai_conversations_owner_recent
    ON ai_conversations (user_id, session_id, last_message_at DESC, id DESC);
CREATE INDEX idx_ai_conversations_session
    ON ai_conversations (session_id) WHERE session_id IS NOT NULL;
CREATE INDEX idx_ai_conversations_last_message
    ON ai_conversations (last_message_at);

CREATE TABLE ai_conversation_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL REFERENCES ai_conversations(id) ON DELETE CASCADE,
    role VARCHAR(9) NOT NULL CHECK (role IN ('user', 'assistant')),
    content TEXT NOT NULL CHECK (char_length(content) BETWEEN 1 AND 32000),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_ai_conversation_messages_order
    ON ai_conversation_messages (conversation_id, id);

CREATE TABLE ai_conversation_summaries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL REFERENCES ai_conversations(id) ON DELETE CASCADE,
    text TEXT NOT NULL CHECK (char_length(text) BETWEEN 1 AND 4000),
    -- source message range (inclusive), message ids of this conversation
    from_message_id BIGINT NOT NULL,
    to_message_id BIGINT NOT NULL,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    superseded_at TIMESTAMP(6) WITH TIME ZONE,
    invalidated_at TIMESTAMP(6) WITH TIME ZONE,
    CONSTRAINT ck_ai_summary_range CHECK (from_message_id <= to_message_id)
);

-- at most one active summary per conversation
CREATE UNIQUE INDEX uk_ai_conversation_summaries_active
    ON ai_conversation_summaries (conversation_id) WHERE superseded_at IS NULL AND invalidated_at IS NULL;
-- superseded / invalidated rows too: the conversation delete cascade looks them up by conversation_id
CREATE INDEX idx_ai_conversation_summaries_conversation
    ON ai_conversation_summaries (conversation_id);

CREATE TABLE ai_memories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    session_id BIGINT REFERENCES study_sessions(id) ON DELETE CASCADE,
    conversation_id BIGINT NOT NULL REFERENCES ai_conversations(id) ON DELETE CASCADE,
    text TEXT NOT NULL CHECK (char_length(text) BETWEEN 1 AND 1000),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_ai_memories_scope_recent
    ON ai_memories (user_id, session_id, created_at DESC);
CREATE INDEX idx_ai_memories_conversation
    ON ai_memories (conversation_id);
-- study_sessions delete cascade
CREATE INDEX idx_ai_memories_session
    ON ai_memories (session_id) WHERE session_id IS NOT NULL;
